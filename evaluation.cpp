namespace Eval{
    int evaluate(Board &board){
        int white_score = 0;
        int black_score = 0;


        for(int p = PAWN; p <= KING; p++){
            uint64_t white_pieces = board.bitboards[WHITE][p];
            while(white_pieces){
                uint8_t sq = __builtin_ctzll(white_pieces);

                white_score += get_pst_value(sq, WHITE, p);
                white_score += piece_value[p];

                white_pieces &= white_pieces - 1;
            }
        }

        for(int p = PAWN; p <= KING; p++){
            uint64_t black_pieces = board.bitboards[BLACK][p];
            while(black_pieces){
                uint8_t sq = __builtin_ctzll(black_pieces);

                black_score += get_pst_value(sq, BLACK, p);
                black_score += piece_value[p];

                black_pieces &= black_pieces - 1;
            }
        }

        int evaluation = white_score - black_score;

        return board.white_to_move ? evaluation : -evaluation;
    }

    int get_pst_value(int square, bool is_white, int piece){
        if(piece == EMPTY) return 0;

        uint8_t target_squre = is_white ? square : (square ^ 56);

        return pst_table[piece][target_squre];
    }
}